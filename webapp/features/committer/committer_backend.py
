import os
import subprocess
from starlette.requests import Request
from starlette.responses import JSONResponse

BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))

def get_repo_files():
    file_list = []
    exclude_dirs = {".git", "__pycache__", ".pytest_cache", "venv", ".venv"}
    for root, dirs, files in os.walk(BASE_DIR):
        dirs[:] = [d for d in dirs if d not in exclude_dirs]
        for f in files:
            if f.endswith((".py", ".html", ".css", ".js", ".json", ".md", ".txt")):
                full_path = os.path.join(root, f)
                rel_path = os.path.relpath(full_path, BASE_DIR).replace("\\", "/")
                file_list.append(rel_path)
    file_list.sort()
    return file_list

async def repo_tree_endpoint(request: Request):
    try:
        files = get_repo_files()
        return JSONResponse({"files": files})
    except Exception as e:
        return JSONResponse({"error": str(e)}, status_code=500)

async def file_content_endpoint(request: Request):
    rel_path = request.query_params.get("path", "").strip()
    if not rel_path or ".." in rel_path:
        return JSONResponse({"error": "Invalid path"}, status_code=400)
    
    full_path = os.path.join(BASE_DIR, rel_path)
    if not os.path.isfile(full_path):
        return JSONResponse({"error": "File not found"}, status_code=404)
        
    try:
        with open(full_path, "r", encoding="utf-8") as f:
            content = f.read()
        return JSONResponse({"content": content})
    except Exception as e:
        return JSONResponse({"error": str(e)}, status_code=500)

async def commit_file_endpoint(request: Request):
    try:
        data = await request.json()
    except Exception:
        return JSONResponse({"error": "Invalid JSON"}, status_code=400)

    rel_path = data.get("file_path", "").strip()
    commit_msg = data.get("commit_message", "").strip()
    content = data.get("content", "")

    if not rel_path or not commit_msg:
        return JSONResponse({"error": "File path and commit message are required"}, status_code=400)

    if ".." in rel_path:
        return JSONResponse({"error": "Invalid file path"}, status_code=400)

    full_path = os.path.join(BASE_DIR, rel_path)
    try:
        os.makedirs(os.path.dirname(full_path), exist_ok=True)
        with open(full_path, "w", encoding="utf-8") as f:
            f.write(content)

        subprocess.run(["git", "add", rel_path], cwd=BASE_DIR, check=True)
        subprocess.run(["git", "commit", "-m", commit_msg], cwd=BASE_DIR, check=True)
        subprocess.run(["git", "push"], cwd=BASE_DIR, check=True)

        return JSONResponse({"ok": True, "message": "Commit pushed successfully"})
    except subprocess.CalledProcessError as e:
        return JSONResponse({"error": f"Git command failed: {e}"}, status_code=500)
    except Exception as e:
        return JSONResponse({"error": str(e)}, status_code=500)