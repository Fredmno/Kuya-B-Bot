import os
import base64
import httpx
from starlette.requests import Request
from starlette.responses import JSONResponse

BASE_DIR = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..", "..", "..")
)

GITHUB_TOKEN = os.environ.get("GITHUB_TOKEN")
GITHUB_REPO = os.environ.get("GITHUB_REPO", "alfredodimaano/Kuya-B-Bot-1")
GITHUB_BRANCH = os.environ.get("GITHUB_BRANCH", "main")

def get_clean_repo():
    repo = os.environ.get("GITHUB_REPO", "alfredodimaano/Kuya-B-Bot-1")
    if "github.com/" in repo:
        repo = repo.split("github.com/")[-1].replace(".git", "").strip("/")
    return repo

async def repo_tree_endpoint(request: Request):
    token = os.environ.get("GITHUB_TOKEN")
    repo = get_clean_repo()
    branch = os.environ.get("GITHUB_BRANCH", "main")

    if not token:
        file_list = []
        exclude = {".git", "__pycache__", ".pytest_cache", "venv", ".venv"}
        for root, dirs, files in os.walk(BASE_DIR):
            dirs[:] = [d for d in dirs if d not in exclude]
            for f in files:
                if f.endswith((".py", ".html", ".css", ".js", ".json", ".md")):
                    rel = os.path.relpath(os.path.join(root, f), BASE_DIR).replace("\\", "/")
                    file_list.append(rel)
        file_list.sort()
        return JSONResponse({"files": file_list})

    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github.v3+json"
    }
    url = f"https://api.github.com/repos/{repo}/git/trees/{branch}?recursive=1"
    try:
        async with httpx.AsyncClient() as client:
            res = await client.get(url, headers=headers, timeout=12.0)
            if res.status_code == 200:
                data = res.json()
                valid_exts = (".py", ".html", ".css", ".js", ".json", ".md", ".txt", ".yml")
                files = [
                    item["path"] for item in data.get("tree", [])
                    if item.get("type") == "blob" and item["path"].endswith(valid_exts)
                ]
                files.sort()
                return JSONResponse({"files": files})
            return JSONResponse({"error": res.text, "files": []}, status_code=res.status_code)
    except Exception as e:
        return JSONResponse({"error": str(e), "files": []}, status_code=500)

async def file_content_endpoint(request: Request):
    rel_path = request.query_params.get("path", "").strip().lstrip("/")
    if not rel_path or ".." in rel_path:
        return JSONResponse({"error": "Invalid path"}, status_code=400)

    token = os.environ.get("GITHUB_TOKEN")
    repo = get_clean_repo()
    branch = os.environ.get("GITHUB_BRANCH", "main")

    if token:
        headers = {
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github.v3+json"
        }
        url = f"https://api.github.com/repos/{repo}/contents/{rel_path}?ref={branch}"
        try:
            async with httpx.AsyncClient() as client:
                res = await client.get(url, headers=headers, timeout=10.0)
                if res.status_code == 200:
                    data = res.json()
                    decoded = base64.b64decode(data.get("content", "")).decode("utf-8", errors="replace")
                    return JSONResponse({"content": decoded})
        except Exception:
            pass

    local_path = os.path.join(BASE_DIR, rel_path)
    if os.path.isfile(local_path):
        try:
            with open(local_path, "r", encoding="utf-8") as f:
                return JSONResponse({"content": f.read()})
        except Exception as e:
            return JSONResponse({"error": str(e)}, status_code=500)

    return JSONResponse({"error": "File not found"}, status_code=404)

async def commit_file_endpoint(request: Request):
    try:
        data = await request.json()
    except Exception:
        return JSONResponse({"error": "Invalid JSON body"}, status_code=400)

    rel_path = data.get("file_path", "").strip().lstrip("/")
    commit_msg = data.get("commit_message", "").strip()
    content_str = data.get("content", "")

    if not rel_path or not commit_msg:
        return JSONResponse({"error": "File path and commit message required"}, status_code=400)

    token = os.environ.get("GITHUB_TOKEN")
    repo = get_clean_repo()
    branch = os.environ.get("GITHUB_BRANCH", "main")

    if not token:
        return JSONResponse({"error": "GITHUB_TOKEN is missing in Render environment variables"}, status_code=500)

    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github.v3+json"
    }
    api_url = f"https://api.github.com/repos/{repo}/contents/{rel_path}"

    try:
        async with httpx.AsyncClient() as client:
            sha = None
            get_res = await client.get(f"{api_url}?ref={branch}", headers=headers)
            if get_res.status_code == 200:
                sha = get_res.json().get("sha")

            encoded_content = base64.b64encode(content_str.encode("utf-8")).decode("utf-8")
            payload = {
                "message": commit_msg,
                "content": encoded_content,
                "branch": branch
            }
            if sha:
                payload["sha"] = sha

            put_res = await client.put(api_url, json=payload, headers=headers)
            if put_res.status_code in (200, 201):
                return JSONResponse({"ok": True, "message": "Commit pushed successfully"})
            else:
                err_text = put_res.json().get("message", put_res.text) if put_res.headers.get("content-type", "").startswith("application/json") else put_res.text
                return JSONResponse({"error": f"GitHub error: {err_text}"}, status_code=put_res.status_code)
    except Exception as e:
        return JSONResponse({"error": str(e)}, status_code=500)
